# Solved by scripts/solve_init_pose.py. The leg values are listed per joint and
# NOT as ".*_hip_pitch_joint"-style regexes on purpose: the hip-pitch axes are
# canted ~30 degrees out of pure-Y (right world axis [0, 0.866, 0.5], left
# [0, 0.866, -0.5]), so a hip-pitch rotation theta carries a 0.5*theta yaw
# component of OPPOSITE SIGN per leg. The legs are not mirror images and a
# symmetric crouch does not put the feet flat -- it drifts each foot ~24 mm
# laterally and leaves a 9 mm height mismatch. G1's and H1-V1's crouch numbers
# cannot be transplanted here.
#
# resolve_expr is first-match-wins in dict order, so the explicit per-joint
# keys must stay ahead of any ".*_" catch-all.
