def resolve_joint_groups(joint_names: tuple[str, ...]) -> dict[str, str]:
  """Map each joint to its actuator group name. Used by the model audit."""
  groups = {
    "X12-320": HIP_KNEE_JOINTS,
    "X8-120": WAIST_YAW_SHOULDER_ELBOW_JOINTS,
    "X8-120x2": ANKLE_WAIST_RP_JOINTS,
    "X6-60": WRIST_ROLL_JOINTS,
    "X4-36": WRIST_PITCH_YAW_HEAD_JOINTS,
  }
  out: dict[str, str] = {}
  for name in joint_names:
    hits = [g for g, pats in groups.items() if any(re.match(p, name) for p in pats)]
    assert len(hits) == 1, f"{name} matched {len(hits)} actuator groups: {hits}"
    out[name] = hits[0]
  return out


