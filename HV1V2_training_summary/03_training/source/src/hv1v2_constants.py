PINNED_ACTION_SCALE = 0.0
PINNED_JOINTS = (
  # The waist carries everything above it and is the cheapest way to move the
  # CoM, but its gains are still interpolated seeds.
  r"waist_yaw_joint$",
  r"waist_roll_joint$",
  r"waist_pitch_joint$",
  # The wrists add six joints of exploration for no locomotion benefit.
  r".*_wrist_roll_joint$",
  r".*_wrist_pitch_joint$",
  r".*_wrist_yaw_joint$",
  # The head does not help the robot walk, and head_pitch's actuator is
  # inferred rather than documented.
  r"head_yaw_joint$",
  r"head_pitch_joint$",
)
# NOTE: every string above is also one of the actuator group patterns, so the
# assignment below overwrites in place and dict order is preserved.
#
# WARNING (carried over from H1-V1): NOTHING PRICES A PINNED JOINT'S OUTPUT.
# action_rate_l2, joint_torques and pose all still see these joints, but the
# policy cannot move them, so their contribution is constant and the network's
# raw output there drifts freely -- H1-V1's deployed policy emits |action| up
# to 36.2 on waist_pitch. Harmless at scale 0.0, but unpinning one without
# adding a cost in the same change makes it slam. This tuple must be identical
# in every env that warm-starts from a policy trained with it.


def _build_action_scale() -> dict[str, float]:
  scale: dict[str, float] = {}
  for actuator in HV1V2_ARTICULATION.actuators:
    assert isinstance(actuator, BuiltinPositionActuatorCfg)
    assert actuator.effort_limit is not None
    for name in actuator.target_names_expr:
      scale[name] = 0.25 * actuator.effort_limit / actuator.stiffness
  for pattern in PINNED_JOINTS:
    assert pattern in scale, f"pinned pattern {pattern!r} is not an actuator group pattern"
    scale[pattern] = PINNED_ACTION_SCALE
  return scale


# X12 0.32, X8 0.15, four-bar 0.15 (both effort and stiffness doubled, so the
# ratio is unchanged), X6 0.075, X4 0.085 -- then 11 joints pinned to 0.0.
HV1V2_ACTION_SCALE: dict[str, float] = _build_action_scale()


