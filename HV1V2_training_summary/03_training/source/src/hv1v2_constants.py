#     waist roll/pitch ~3.5x. The X8-120 "1.16x kp" question (true output
#     torque vs telemetry scale) is absorbed by the DR ranges in env_cfgs.py
#     (V11_ANKLE_*_K, V11_WAIST_RP_K) instead of being decided.
#   * waist_yaw runs 400/24 on the robot since 2026-10-26; v1-v10 trained it
#     at the X8 group's 200/12. v11 trains what runs.
#   * Torque: the MJCF's joint actuatorfrcrange caps every joint at its
#     CONTINUOUS rating (hip/knee 85, ankles 43 -- a single X8's, not the
#     pair's 86), so every earlier policy trained without the peak torque the
#     robot actually uses (ankle motor -150 N.m measured on 10-19). v11 lifts
#     the joint caps to the actuator PEAK; joint_torques still prices torque.
