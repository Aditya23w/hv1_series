# Collisions.
##

# The feet carry four flat pads each rather than a convex hull of the foot
# mesh: the real sole is two contact patches (heel ~83x100 mm, toe ~86x117 mm)
# separated by an arch that stands 6-8 mm proud, and a hull would fill that in.
FOOT_GEOM_RE = r"^(left|right)_foot[1-4]_collision$"
FOOT_GEOM_NAMES = tuple(
  f"{side}_foot{i}_collision" for side in ("left", "right") for i in range(1, 5)
)
FOOT_SITE_NAMES = ("left_foot", "right_foot")

# '$'-anchored throughout: filter_exp is prefix-anchored, so an unanchored
# ".*_col" would also swallow the foot pads.
_ANY_COLLISION = r".*_collision$"

FULL_COLLISION = CollisionCfg(
  geom_names_expr=(_ANY_COLLISION,),
  contype=1,
  conaffinity=1,
  # Feet need friction against the terrain; the rest only needs to not
  # interpenetrate, and condim 1 is much cheaper.
  condim={FOOT_GEOM_RE: 3, _ANY_COLLISION: 1},
  priority={FOOT_GEOM_RE: 1, _ANY_COLLISION: 0},
  friction={FOOT_GEOM_RE: (0.6,)},
)

# Bring-up only: feet collide with the terrain, nothing self-collides.
FEET_ONLY_COLLISION = CollisionCfg(
  geom_names_expr=(FOOT_GEOM_RE,),
  contype=0,
  conaffinity=1,
  condim=3,
  priority=1,
  friction=(0.6,),
)


def get_hv1v2_robot_cfg(
  collisions: tuple[CollisionCfg, ...] = (FULL_COLLISION,),
) -> EntityCfg:
  """A fresh HV1V2 EntityCfg (new instance each call, so callers can mutate)."""
  return EntityCfg(
    init_state=HOME_KEYFRAME,
    spec_fn=get_spec,
    articulation=HV1V2_ARTICULATION,
    collisions=collisions,
    # MuJoCo's joint order for this model is already the canonical hardware
    # order (verified identical to config/joint_names_*.yaml). Sorting the
    # actuators to match makes ctrl[i], action[i] and hardware actuator i the
    # same index, so nothing has to be remapped on deploy.
    # Changing this later renumbers every action and invalidates checkpoints.
    sort_actuators=True,
  )


