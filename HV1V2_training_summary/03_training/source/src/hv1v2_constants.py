"""HV1V2 robot definition for mjlab: plant, collisions, initial state.

The MJCF is generated by ``mjcf/urdf2mjcf.py --target robot`` from
``urdf/HV1V2_URDF_NEW_FOOT_V1_220926.urdf``. Regenerate with that script rather
than hand-editing the XML.

Sources for the numbers below:
  [DS]  ACTUATOR_DATASHEET.txt        vendor data for the MyActuator RMD
                                      X-series modules, plus the joint map.
  [S3]  h1v1_lab/ACTUATORS.txt S3     the H1-V1 simulation plant (kp/kd), which
                                      HV1V2 shares actuator families with.
Anything not from those two is marked inline.
"""

