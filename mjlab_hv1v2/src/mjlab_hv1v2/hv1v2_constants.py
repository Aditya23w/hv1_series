def get_spec_v11() -> mujoco.MjSpec:
  """get_spec() with every joint's actuatorfrcrange raised to the actuator peak."""
  spec = get_spec()
  for j in spec.joints:
    if j.type != mujoco.mjtJoint.mjJNT_HINGE:
      continue
    hits = [v for p, v in V11_PEAK_TORQUE.items() if re.match(p, j.name)]
    assert len(hits) == 1, f"{j.name}: {len(hits)} V11_PEAK_TORQUE matches"
    j.actfrclimited = mujoco.mjtLimited.mjLIMITED_TRUE
    j.actfrcrange = [-hits[0], hits[0]]
  return spec


def get_hv1v2_v11_robot_cfg(
  collisions: tuple[CollisionCfg, ...] = (FULL_COLLISION,),
) -> EntityCfg:
  """The v11 plant: HOME_KEYFRAME, peak joint torque caps, waist yaw 400/24."""
