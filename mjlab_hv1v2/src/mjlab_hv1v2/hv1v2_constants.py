# Sensors the mjlab velocity task resolves by name (as robot/<name>).
_REQUIRED_SENSORS = ("imu_lin_vel", "imu_ang_vel", "root_angmom")


def get_spec() -> mujoco.MjSpec:
  """Load the HV1V2 training MJCF.

  Defensive, not repairing: the generator is supposed to emit a spec that is
  already correct, so anything fixed up here would be a stale asset. We delete
  what mjlab must own and assert the rest.
  """
  spec = mujoco.MjSpec.from_file(str(HV1V2_XML))

  # mjlab builds <position> actuators from the config below.
  for actuator in list(spec.actuators):
    spec.delete(actuator)

  # Scene._add_entities() takes spec.keys[0] and only warns about the others,
  # so a stray keyframe would silently override the configured initial state.
  for key in list(spec.keys):
    spec.delete(key)

  names = {s.name for s in spec.sensors}
  missing = [s for s in _REQUIRED_SENSORS if s not in names]
  assert not missing, (
    f"{HV1V2_XML.name} is missing sensors {missing}; the velocity task looks "
    "them up by name. Regenerate with: "
    "python mjcf/urdf2mjcf.py --target robot"
  )
  return spec


