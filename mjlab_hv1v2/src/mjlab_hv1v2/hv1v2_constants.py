# ---------------------------------------------------------------------------
# PROVISIONAL: armature.
#
# Every armature below is the published "Inertia (kg.cm2)" times ratio^2, i.e.
# the value IF that column is motor-side. [DS] note 2 is explicit that the
# vendor never states what it is referred to. If it is already output-side,
# these are ~400x too large.
#
# This is the weakest number in the plant, and armature sets the
# high-frequency response the policy learns against. Two consequences that are
# deliberate, not oversights:
#   * joint_armature domain randomisation is (0.6, 1.4) here, wider than the
#     (0.8, 1.2) H1-V1 uses, so a policy is robust across the uncertainty
#     rather than fitted to the middle of it;
#   * these values diverge from H1-V1's deployed plant (0.326938 / 0.041 /
#     0.009934 / 0.0034 -- 1.4x to 11x smaller, by a non-constant factor), so
#     an HV1V2 policy is NOT plant-compatible with an H1-V1 one.
#
# To settle it: free-swing pendulum-decay on one X12 joint, the same
# measurement that settled X8-120 for H1-V1 (1.44 N.m, within 4% of the
# vendor's back-drive torque). When that lands, add a _V2 group rather than
# editing these in place -- h1v1_constants.py records that an in-place edit
# silently changed the plant for thirteen registered tasks at once.
# ---------------------------------------------------------------------------
ARMATURE_PROVENANCE = "vendor J*ratio^2, motor-side assumption UNCONFIRMED"

