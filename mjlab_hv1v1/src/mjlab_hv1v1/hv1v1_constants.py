"""HV1V1 robot definition for mjlab: plant, collisions, initial state.

HV1V1 is the OLDER-FOOT variant of the same body as HV1V2. Verified against
both URDFs: every joint name, limit, velocity, origin xyz/rpy and the whole
actuator map are IDENTICAL; every link mass matches within 1% except the feet.

  foot mass          0.9691 -> 1.7823 kg each   (+84%)
  foot CoM vs ankle   +29.5 -> +65.9 mm
  sole about ankle   -95.9..+167.1 -> -62.0..+219.5 mm
  ankle along sole    36.5% -> 22.0% from the heel
  total mass         92.6824 -> 94.3088 kg

The plant below is therefore HV1V2's unchanged. What had to be re-derived is
the initial pose and the foot pads, because the support centre moved 43.1 mm
forward.

An earlier version of this paragraph claimed the solved pose "removes" the need
for the ad-hoc ~2.5 deg ankle offset that an HV1V2 policy needs on this robot.
THE HARDWARE DISPROVED THAT: HV1V1's own from-scratch policy does not balance
without the offset either, so it is a property of the ROBOT, not of a mismatch
between an HV1V2 policy and an HV1V1 foot. The offset is now TRAINED IN -- see
the ankle bias note on HOME_KEYFRAME.

NAMING: the source export is called URDF_HV1V2_26092026 even though it is the
old-foot robot. The foot geometry identifies it, not the filename.

The MJCF is generated by ``mjcf/urdf2mjcf.py --target robot`` from
``urdf/HV1V1_URDF_NEW_FOOT_V1_220926.urdf``. Regenerate with that script rather
than hand-editing the XML.

Sources for the numbers below:
  [DS]  ACTUATOR_DATASHEET.txt        vendor data for the MyActuator RMD
                                      X-series modules, plus the joint map.
  [S3]  h1v1_lab/ACTUATORS.txt S3     the H1-V1 simulation plant (kp/kd), which
                                      HV1V1 shares actuator families with.
Anything not from those two is marked inline.
"""

