ACTION_SCALE_OVERRIDES: dict[str, float] = {}


def _build_action_scale() -> dict[str, float]:
  scale: dict[str, float] = {}
  for actuator in HV1V1_ARTICULATION.actuators:
    assert isinstance(actuator, BuiltinPositionActuatorCfg)
    assert actuator.effort_limit is not None
    for name in actuator.target_names_expr:
      scale[name] = 0.25 * actuator.effort_limit / actuator.stiffness
  # Overrides first, so a joint that is BOTH overridden and pinned still ends up
  # pinned -- pinning is the stronger statement and must win.
  for pattern, value in ACTION_SCALE_OVERRIDES.items():
    assert pattern in scale, f"override pattern {pattern!r} is not an actuator group pattern"
    scale[pattern] = value
  for pattern in PINNED_JOINTS:
    assert pattern in scale, f"pinned pattern {pattern!r} is not an actuator group pattern"
    scale[pattern] = PINNED_ACTION_SCALE
  return scale


# X12 0.32, X8 0.15, four-bar 0.15 (both effort and stiffness doubled, so the
# ratio is unchanged), X6 0.075, X4 0.085 -- then 11 joints pinned to 0.0.
HV1V1_ACTION_SCALE: dict[str, float] = _build_action_scale()


def resolve_joint_groups(joint_names: tuple[str, ...]) -> dict[str, str]:
  """Map each joint to its actuator group name. Used by the model audit."""
  groups = {
    "X12-320": HIP_KNEE_JOINTS,
    "X8-120": WAIST_YAW_SHOULDER_ELBOW_JOINTS,
    "X8-120x2": ANKLE_WAIST_RP_JOINTS,
    "X6-60": WRIST_ROLL_JOINTS,
    "X4-36": WRIST_PITCH_YAW_HEAD_JOINTS,
  }
  out: dict[str, str] = {}
  for name in joint_names:
    hits = [g for g, pats in groups.items() if any(re.match(p, name) for p in pats)]
    assert len(hits) == 1, f"{name} matched {len(hits)} actuator groups: {hits}"
    out[name] = hits[0]
  return out


