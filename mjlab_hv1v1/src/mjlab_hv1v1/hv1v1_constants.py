# Solved by scripts/solve_init_pose.py. The leg values are listed per joint and
# NOT as ".*_hip_pitch_joint"-style regexes on purpose: the hip-pitch axes are
# canted ~30 degrees out of pure-Y (right world axis [0, 0.866, 0.5], left
# [0, 0.866, -0.5]), so a hip-pitch rotation theta carries a 0.5*theta yaw
# component of OPPOSITE SIGN per leg. The legs are not mirror images and a
# symmetric crouch does not put the feet flat -- it drifts each foot ~24 mm
# laterally and leaves a 9 mm height mismatch. G1's and H1-V1's crouch numbers
# cannot be transplanted here.
#
# resolve_expr is first-match-wins in dict order, so the explicit per-joint
# keys must stay ahead of any ".*_" catch-all.
# Solved by scripts/solve_init_pose.py against HV1V1's OWN foot, targeting
# COM_SOLE_FRACTION = 0.345 -- the CoM at 34.50% ACHIEVED along the sole, i.e.
# +35.09 mm ahead of the ankle. Verified: feet flat, stance 0.24304 m, zero
# stagger, zero height mismatch, pads on the floor to 4 um, no self-contacts,
# 0.234 rad soft-limit slack, margins 97.1 mm rear / 184.7 mm front.
#
# RE-SOLVED 2026-10-20 after urdf2mjcf.py moved the left knee axis onto its
# bore (the SolidWorks export had it 11.9 mm off, same as HV1V2). The old
# knees (right 0.376, left 0.324) were mostly the solver compensating for that
# error; they are now 0.350 / 0.350. Policies trained before this date used
# HOME_KEYFRAME_PRE_KNEE_FIX below, and their checkpoints must be played,
# evaluated and re-exported with it, not with this pose.
#
# THERE IS NO 2.5 DEG ANKLE OFFSET HERE, AND NONE BELONGS HERE. The offset that
# was needed on hardware was a POLICY-TRANSFER artifact: HV1V2's anchor puts its
# CoM at 50.0% along its own sole, and running HV1V2's joint angles on this foot
# lands at only 34.6% (a ~43 mm foot-relative MISMATCH), which is consistent
# with the heel-biased loading and backward drive that were observed. CoP/ZMP
# was not directly measured, so that is the best-supported explanation rather
# than a measurement. A policy trained from scratch on HV1V1 learns its own
# foot-relative convention, so the offset must not be baked in here.
#
# NOTE that this pose sits at 34.35%, i.e. essentially WHERE HV1V2'S ANGLES LAND
# on this foot. That is deliberate and it is not a contradiction: what failed on
# hardware was the DISAGREEMENT between a 50%-trained policy and a 34.6% robot,
# not the position itself. Training here removes the disagreement.
#
# WHY NOT FURTHER FORWARD. Every anchor pose is a PD-held inverted pendulum and
# none is passively stable, so the discriminator is how fast it diverges relative
# to the pose that is KNOWN to train. Measured through one code path -- creep
# fitted over 0.5-2.5 s, torque taken only while |dz| < 15 mm so the fall is
# excluded:
#
#   HV1V2 committed, 50.0%   54.6 N.m (64% cont)   -0.83 mm/s   falls  3.91 s
#   HV1V1  34.4% (this pose) 31.1 N.m (36% cont)   -0.21 mm/s   falls  6.24 s
#   HV1V1  41.3% (+54.4 mm)  49.2 N.m (57% cont)  -19.85 mm/s   falls  1.35 s
#   HV1V1  49.8% (+78.3 mm)  43.9 N.m (51% cont)  -47.32 mm/s   falls  0.89 s
#
# 34.4% is the only HV1V1 option at or better than HV1V2's proven creep, and it
# beats it on all three measures. It also has the LARGEST front margin, which is
# the right way round: v4 survived 3x backward and lateral pushes and fell only
# forward. Its cost is the smallest rear margin, 96.7 mm, which is still ample.
#
# The "m*g*x / ankle capacity" duty argument that earlier pushed this pose
# forward is WRONG for a robot on flat feet -- mj_inverse puts the real static
# ankle requirement at -1.59 N.m here and -0.52 N.m on HV1V2, ~60x below that
# formula, because the ground reaction supplies the moment by shifting its CoP.
# See the note at the top of solve_init_pose.py.
#
# ANKLE BIAS: both ankle_pitch values carry +2.7 deg (+0.047124 rad) of
# PLANTARFLEXION on top of the feet-flat solve. Not a solver artifact -- it is
# what makes this robot walk, and solve_init_pose.py applies it explicitly via
# ANKLE_PITCH_BIAS_DEG. With the foot planted it holds a constant plantarflexion
# torque, driving the centre of pressure onto the toe and the body forward;
# without it the robot loads its heels and drives backwards on hardware. The
# pelvis is 11.4 mm above the feet-flat solve because the heel lifts.
#
# WHEN DEPLOYING: the robot's own ankle offset must be set to ZERO. This anchor
# already contains it; leaving a hardware offset on top gives 5.4 deg.
#
# The remaining left/right asymmetry is real, not a typo: the hip-pitch axes
# are canted ~30 deg and the legs are not mirror images.
