#!/usr/bin/env python3
"""Build the MNN deployment folder for a trained HV1V1 policy.

Takes the ONNX bundle that export_deploy.py produced, converts the graph to MNN
and writes the robot-side configs. Everything is DERIVED from deploy.json -- no
value is typed twice, so the YAML the robot reads and the anchor the policy was
trained against cannot drift apart. That is the whole point: a converted model
plus a hand-maintained config is the classic way to ship a policy that runs but
walks wrong.

  python mjlab_hv1v1/scripts/export_mnn.py --run v5

Needs `mnnconvert` on PATH (pip install MNN). Run verify_mnn.py afterwards --
conversion succeeding tells you nothing about whether the numbers match.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# What the robot is ALLOWED to be commanded, as a deliberate subset of what the
# policy was trained on. The policy has never been driven at its full trained
# envelope on this machine, and a command it has not seen is the cheapest way to
# put it on the floor. Widen once it walks.
DEPLOY_VEL = {
  "lin_vel_x": (-0.4, 0.8),
  "lin_vel_y": (-0.3, 0.3),
  "ang_vel_z": (-0.4, 0.4),
}


def sha256(p: Path) -> str:
  h = hashlib.sha256()
  with p.open("rb") as f:
    for chunk in iter(lambda: f.read(1 << 20), b""):
      h.update(chunk)
  return h.hexdigest()


def yaml_scalar(v) -> str:
  if isinstance(v, bool):
    return "true" if v else "false"
  if isinstance(v, (int,)):
    return str(v)
  if isinstance(v, float):
    return f"{v:.6g}"
  return f'"{v}"'


def main() -> int:
  ap = argparse.ArgumentParser()
  ap.add_argument("--run", default="v5")
  ap.add_argument("--out", default=None)
  ap.add_argument("--stem", default=None, help="basename of the .mnn (default walk_hv1v1_<run>)")
  args = ap.parse_args()

  src = ROOT / "exported" / f"deploy_{args.run}"
  if not src.exists():
    sys.exit(f"{src} missing -- run export_deploy.py --run {args.run} first")
  out = Path(args.out) if args.out else ROOT / "exported" / f"mnn_{args.run}"
  out.mkdir(parents=True, exist_ok=True)
  stem = args.stem or f"walk_hv1v1_{args.run}"

  cfg = json.loads((src / "deploy.json").read_text())
  jn = [j["name"] for j in cfg["joints"]]
  anchor = cfg["anchor"]["default_joint_pos"]
  scale = cfg["action"]["scale"]
  kp, kd = cfg["gains"]["kp"], cfg["gains"]["kd"]
  four_bar = set(cfg["four_bar_warning"]["joints"])

  shutil.copy2(src / "policy.onnx", out / "policy.onnx")
  shutil.copy2(src / "deploy.json", out / "deploy.json")

  # --- convert ---------------------------------------------------------------
  mnn = out / f"{stem}.mnn"
  print(f"converting -> {mnn.name}")
  # mnnconvert ships in the interpreter's own bin/, which is NOT on PATH when
  # python is invoked by absolute path. Prefer the sibling binary, fall back to
  # PATH, and say so clearly rather than dying in subprocess.
  exe = Path(sys.executable).parent / "mnnconvert"
  if not exe.exists():
    found = shutil.which("mnnconvert")
    if not found:
      sys.exit("mnnconvert not found -- `pip install MNN` into this interpreter")
    exe = Path(found)
  r = subprocess.run(
    [str(exe), "-f", "ONNX", "--modelFile", str(out / "policy.onnx"),
     "--MNNModel", str(mnn), "--bizCode", "hv1v1"],
    capture_output=True, text=True,
  )
  if "Converted Success" not in (r.stdout + r.stderr):
    print(r.stdout[-2000:], r.stderr[-2000:])
    sys.exit("mnnconvert failed")

  # --- policy_service.yaml ---------------------------------------------------
  obs_terms = cfg["policy"]["observation"]
  L = [
    "# HV1V1 policy service config -- GENERATED by export_mnn.py, do not hand-edit.",
    "# Every value is derived from deploy.json, which is written from the trained",
    "# model. Editing here silently desynchronises the robot from the policy.",
    "",
    f"robot: hv1v1",
    f"run: {yaml_scalar(cfg['meta']['run'])}",
    f"iterations: {cfg['meta']['iterations']}",
    f"exported_utc: {yaml_scalar(cfg['meta']['exported_utc'])}",
    "",
    "model:",
    f"  file: {yaml_scalar(mnn.name)}",
    f"  format: mnn",
    f"  input_name: {yaml_scalar(cfg['policy']['input_name'])}",
    f"  output_name: {yaml_scalar(cfg['policy']['output_name'])}",
    f"  obs_dim: {cfg['policy']['obs_dim']}",
    f"  action_dim: {cfg['policy']['action_dim']}",
    "",
    "control:",
    f"  rate_hz: {cfg['control']['control_hz']:g}            # policy / target update rate",
    f"  control_dt: {cfg['control']['control_dt']:g}",
    f"  pd_rate_hz_min: 200       # the joint PD must run AT LEAST this fast; see README",
    f"  root_body: {yaml_scalar(cfg['control']['root_body'])}",
    "",
    "# Term-major, oldest frame first. Assemble in exactly this order.",
    "# At t=0 BACKFILL every history slot with the first reading; never zero-fill.",
    "observation:",
  ]
  for t in obs_terms:
    L.append(f"  - name: {t['name']}")
    L.append(f"    dim: {t['dim']}")
    L.append(f"    history: {t['history']}")
  L += [
    "",
    "# target[i] = anchor[i] + action[i] * action_scale[i]",
    "# 11 joints have action_scale 0.0: the policy cannot move them, hold at anchor.",
    "joints:",
  ]
  for j in cfg["joints"]:
    n = j["name"]
    L += [
      f"  - name: {n}",
      f"    index: {j['index']}",
      f"    anchor: {anchor[n]:+.6f}",
      f"    action_scale: {scale[n]:g}",
      f"    kp: {kp[n]:g}",
      f"    kd: {kd[n]:g}",
      f"    lower: {j['lower']:+.4f}",
      f"    upper: {j['upper']:+.4f}",
      f"    effort_peak_nm: {j['effort_peak_nm']:g}",
      f"    four_bar: {'true' if n in four_bar else 'false'}",
    ]
  L += [
    "",
    "# What the operator may command. A SUBSET of the trained envelope on purpose.",
    "command_limits:",
  ]
  for k, (lo, hi) in DEPLOY_VEL.items():
    tr = cfg["commands"]["trained_ranges"][k]
    L.append(f"  {k}: [{lo:g}, {hi:g}]      # trained on [{tr[0]:g}, {tr[1]:g}]")
  L += [
    "",
    "warnings:",
    "  ankle_offset_must_be_zero: true   # the anchor already carries +2.7 deg; see README",
    "  four_bar_gain_unmeasured: true    # do not write kp straight to the motors",
    "",
  ]
  (out / "policy_service.hv1v1.yaml").write_text("\n".join(L))

  # --- ready_pose.yaml -------------------------------------------------------
  rp = cfg["ready_pose"]
  R = [
    "# HV1V1 ready pose -- GENERATED by export_mnn.py, do not hand-edit.",
    "# Servo here with joint PD, then hand over to the policy. Identical to the",
    "# action anchor, so the handover is bumpless.",
    "#",
    "# This pose does NOT stand on its own. Keep the policy running.",
    "#",
    "# The two ankle_pitch values carry +2.7 deg of plantarflexion that the policy",
    "# was TRAINED with. The robot's own ankle offset must be ZERO.",
    "",
    f"pelvis_height_m: {rp['pelvis_height_m']:g}",
    f"stance: {yaml_scalar(rp['feet'])}",
    "joint_pos:",
  ]
  for n in jn:
    R.append(f"  {n}: {anchor[n]:+.6f}")
  (out / "ready_pose.hv1v1.yaml").write_text("\n".join(R) + "\n")

  # --- joint table -----------------------------------------------------------
  T = [
    f"# HV1V1 joint table -- run `{cfg['meta']['run']}`, iteration {cfg['meta']['iterations']}",
    "",
    "Order is **ctrl order** and is the order the policy's 31 outputs arrive in.",
    "Do not reorder. `kp`/`kd` are SIMULATION joint-space gains; for the six",
    "four-bar joints (**4B**) they are the DOUBLED values -- see the README.",
    "",
    "| # | joint | actuator | anchor rad | scale | commandable rad | limits rad | kp | kd | peak N·m |",
    "|---|---|---|---|---|---|---|---|---|---|",
  ]
  for j in cfg["joints"]:
    n = j["name"]
    a, s = anchor[n], scale[n]
    win = "—  (pinned)" if s == 0.0 else f"{a - s:+.3f} … {a + s:+.3f}"
    tag = " **4B**" if n in four_bar else ""
    T.append(f"| {j['index']} | `{n}`{tag} | {j['actuator']} | {a:+.5f} | {s:.3f} | {win} "
             f"| {j['lower']:+.3f} … {j['upper']:+.3f} | {kp[n]:.0f} | {kd[n]:.1f} "
             f"| {j['effort_peak_nm']:.0f} |")
  pinned = [n for n in jn if scale[n] == 0.0]
  T += ["", f"**{len(jn) - len(pinned)} live**, **{len(pinned)} pinned at scale 0.0** "
        "(hold them at the anchor).", "",
        "Pinned: " + ", ".join(f"`{p}`" for p in pinned), ""]
  (out / "_joint_table.md").write_text("\n".join(T))

  # --- checksums -------------------------------------------------------------
  files = sorted(p for p in out.iterdir() if p.is_file() and p.name != "checksums.txt")
  (out / "checksums.txt").write_text(
    "".join(f"{sha256(p)}  {p.name}\n" for p in files))

  print(f"\nwrote {out}")
  for p in sorted(out.iterdir()):
    print(f"   {p.name:34s}{p.stat().st_size / 1024:9.1f} KiB")
  print("\n  NOW RUN: python verify_mnn.py   (conversion success != numerical match)")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
